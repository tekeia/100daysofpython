crossroad = input("You're at a cross road. Where do you want to go?\n   "
                  "Type \"left\" or \"right\"\n").lower()

if crossroad == "right":
    print("Game Over!")
else:
    river = input("You encounter a river. What do you want to do?\n   "
                  "Type \"swim\" or \"wait\"\n").lower()
    if river == "swim":
        print("Game Over!")
    else:
        door = input("You wait, look around and find three doors. "
                     "A blue, red and yellow one. Which one do you take?\n   "
                     "Type \"red\" or \"blue\" or \"yellow\"\n").lower()
        if door == "yellow":
            print("You win!")
        else:
            print("Game Over!")